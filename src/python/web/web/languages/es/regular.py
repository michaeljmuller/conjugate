# Respellings that keep an -ar stem's final consonant sounding the same when the
# ending starts with a front vowel. Tried in order, first match wins, so "gu" is
# listed before "g".
_AR_RESPELL = (
    ("gu", "gü"),   # averiguar -> averigüé
    ("c", "qu"),    # buscar -> busqué
    ("g", "gu"),    # llegar -> llegué
    ("z", "c"),     # cruzar -> crucé
)

# The same for an -er/-ir stem before a back vowel. "gu" and "qu" precede the
# bare letters they contain.
_ER_IR_RESPELL = (
    ("gu", "g"),    # distinguir -> distingo
    ("qu", "c"),    # delinquir -> delinco
    ("c", "z"),     # vencer -> venzo
    ("g", "j"),     # coger -> cojo
)

# Accented vowels count: an -ar verb's preterite "yo" ending is "é", and
# "buscé" would be as wrong as "busce".
_FRONT_VOWELS = frozenset("eiéí")
_BACK_VOWELS = frozenset("aoáó")


def _respell(pattern: str) -> tuple[tuple[tuple[str, str], ...], frozenset[str]]:
    """The respelling table and triggering vowels for a pattern."""
    if pattern == "ar":
        return _AR_RESPELL, _FRONT_VOWELS
    return _ER_IR_RESPELL, _BACK_VOWELS


def _infinitive_ending(infinitive: str) -> str | None:
    """``ar``/``er``/``ir``, or ``None`` outside the three conjugations."""
    for ending in PATTERNS:
        if infinitive.endswith(ending) and len(infinitive) > len(ending):
            return ending
    return None


def patterns_for(infinitive: str) -> list[str]:
    """Which regular patterns this infinitive could follow — at most one.

    Spanish gives no ``-ire``-style ambiguity: the ending names the conjugation.
    The list is kept for the same shape as the other languages' checks.
    """
    ending = _infinitive_ending(infinitive)
    return [ending] if ending else []


def _join(stem: str, ending: str, pattern: str) -> str:
    """Stem + ending, respelling the stem where the ending's vowel demands it."""
    table, vowels = _respell(pattern)
    if not ending or ending[0] not in vowels:
        return stem + ending
    for old, new in table:
        if stem.endswith(old):
            return stem[: len(stem) - len(old)] + new + ending
    return stem + ending


def regular_forms(
    infinitive: str, pattern: str
) -> dict[tuple[str, str], tuple[str, ...]] | None:
    """Every simple-tense cell a verb of this shape would have under ``pattern``.

    Each cell maps to *all* the forms the pattern accepts there, which is more
    than one for the imperfect subjunctive: ``hablara`` and ``hablase`` are both
    regular, and treating either as an irregularity would call every Spanish
    verb irregular.

    ``None`` if the infinitive is outside the three conjugations, or the pattern
    does not apply to it.
    """
    if pattern not in patterns_for(infinitive):
        return None
    index = PATTERNS.index(pattern)
    stem = infinitive[:-2]
    return {
        key: tuple(_join(stem, ending, pattern) for ending in endings[index])
        for key, endings in ENDINGS.items()
    }


# Cells to quote a spelling change from, most recognisable first.
_EXAMPLE_CELLS = (
    ("preterito", "yo"),
    ("presente", "yo"),
    ("subjuntivo_presente", "yo"),
)


@dataclass(frozen=True)
class Spelling:
    """A stem respelling that runs through a whole paradigm predictably."""

    old: str
    new: str
    before: str  # the vowels that trigger it, e.g. "e/é"
    examples: tuple[str, ...]

    def describe(self) -> str:
        return f"{self.old} → {self.new} before {self.before} ({', '.join(self.examples)})"


def spelling_change(infinitive: str) -> Spelling | None:
    """The one respelling this verb's stem needs, if any."""
    patterns = patterns_for(infinitive)
    if not patterns:
        return None
    pattern = patterns[0]
    index = PATTERNS.index(pattern)
    stem = infinitive[:-2]
    table, vowels = _respell(pattern)

    change = next(((o, n) for o, n in table if stem.endswith(o)), None)
    if change is None:
        return None

    triggering = sorted(
        {
            ending[0]
            for e in ENDINGS.values()
            for ending in e[index]
            if ending and ending[0] in vowels
        }
    )
    # Deduplicated: several cells share an ending, so quoting them all would
    # print "busque, busque" instead of "busqué, busque".
    examples: list[str] = []
    for key in _EXAMPLE_CELLS:
        if key not in ENDINGS:
            continue
        ending = ENDINGS[key][index][0]
        form = _join(stem, ending, pattern)
        if form != stem + ending and form not in examples:
            examples.append(form)
    return Spelling(*change, before="/".join(triggering), examples=tuple(examples[:2]))


@dataclass(frozen=True)
class Classification:
    kind: str
    pattern: str | None = None
    spelling: Spelling | None = None

    @property
    def is_regular(self) -> bool:
        return self.kind != IRREGULAR

    def describe(self) -> str:
        """The verdict as a clause to follow the infinitive."""
        if self.kind == IRREGULAR:
            return "is an irregular verb."
        named = PATTERN_NAMES.get(self.pattern, self.pattern)
        if self.kind == REGULAR:
            return f"is a regular {named} verb."
        return (
            f"is a regular {named} verb, apart from a spelling change: "
            f"{self.spelling.describe()}."
        )


def classify(paradigm: Paradigm) -> Classification:
    """Predictable, predictable-but-respelt, or worth drilling.

    Deliberately strict: the cells the table covers must match one pattern
    exactly, so a verb carrying an extra accepted form anywhere is irregular.
    That form is the whole reason to drill it.

    The compound tenses take no part. They are *haber* plus the participle, and
    the participle row is already being checked, so a paradigm that satisfies
    the table has regular compounds by construction.
    """
    for pattern in patterns_for(paradigm.infinitive):
        expected = regular_forms(paradigm.infinitive, pattern)
        if expected is None:
            continue
        covered = {key: cell for key, cell in paradigm.cells.items() if key in expected}
        if set(covered) != set(expected):
            continue
        # Compared as sets: which of several equally regular forms the source
        # happens to list first is not a signal about the verb.
        if not all(set(cell.forms) == set(expected[key]) for key, cell in covered.items()):
            continue
        change = spelling_change(paradigm.infinitive)
        return (
            Classification(REGULAR_WITH_SPELLING, pattern, change)
            if change
            else Classification(REGULAR, pattern)
        )
    return Classification(IRREGULAR)


def is_regular(paradigm: Paradigm) -> bool:
    """True when the paradigm holds nothing the ending table doesn't predict."""
    return classify(paradigm).is_regular
