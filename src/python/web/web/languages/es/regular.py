# What the check can conclude about a verb.
REGULAR = "regular"
REGULAR_WITH_SPELLING = "regular_with_spelling"
IRREGULAR = "irregular"

# The three regular patterns, in the order the ending table's columns run.
PATTERNS = ("ar", "er", "ir")

# How each pattern is named to the user.
PATTERN_NAMES = {"ar": "-ar", "er": "-er", "ir": "-ir"}

