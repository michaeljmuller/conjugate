"""How predictable is this Italian verb, given its infinitive?

Adding a verb stops to confirm, and this is what that confirmation reports —
the same three verdicts as the Portuguese check, reached the same way, but over
Italian's own patterns.

Italian has **four** regular patterns where Portuguese has three. ``-ire``
splits in two: the plain conjugation (``partire`` → ``parto``) and the one that
infixes ``-isc-`` in the singular and third plural (``capire`` → ``capisco``,
``capisca``). Both are completely regular; which a verb takes simply is not
recoverable from the infinitive, so an ``-ire`` verb is checked against both and
counts as regular if it matches either.

The spelling changes are Italian's own and go the opposite way from Portuguese's.
An ``-are`` stem is written against a back vowel, so a front-vowel ending
disturbs it: ``cercare`` → ``cerchi`` keeps the /k/, ``pagare`` → ``paghi``
keeps the /g/, and ``cominciare`` → ``cominci`` drops an ``i`` that would
otherwise double. ``-ere`` and ``-ire`` need none: Italian simply lets ``leggo``
and ``leggi`` differ in sound at the same spelling.

The table is not typed from memory. ``tools/italian_endings.py`` regenerates it
by fetching Reverso's own ``parlare`` / ``credere`` / ``partire`` / ``capire``
and subtracting the stem, so the endings come from the same source as the verbs
they are compared against.

Errors here are one-sided by construction, as in Portuguese: a missing spelling
rule makes a regular verb look irregular, understating how predictable it is,
while the reverse would need the table to reproduce an irregular paradigm
exactly, which it cannot.
"""

