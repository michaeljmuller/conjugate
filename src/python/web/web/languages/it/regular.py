# Respellings that keep an -are stem's final consonant sounding the same when
# the ending starts with a front vowel. Tried in order, first match wins — so
# "sci" is listed before "ci", and "ci"/"gi" before bare "c"/"g".
_ARE_RESPELL = (
    ("sci", "sc"),   # lasciare -> lasci, lascerò
    ("ci", "c"),     # cominciare -> cominci, comincerò
    ("gi", "g"),     # mangiare -> mangi, mangerò
    ("c", "ch"),     # cercare -> cerchi, cercherò
    ("g", "gh"),     # pagare -> paghi, pagherò
)
_FRONT_VOWELS = frozenset("ei")


def _infinitive_ending(infinitive: str) -> str | None:
    """``are``/``ere``/``ire``, or ``None`` outside the three conjugations."""
    for ending in ("are", "ere", "ire"):
        if infinitive.endswith(ending) and len(infinitive) > len(ending):
            return ending
    return None


def patterns_for(infinitive: str) -> list[str]:
    """Which regular patterns this infinitive could follow.

    One for ``-are`` and ``-ere``; two for ``-ire``, which gives no clue
    whether the verb infixes ``-isc-``.
    """
    ending = _infinitive_ending(infinitive)
    if ending is None:
        return []
    return ["ire", "ire-isc"] if ending == "ire" else [ending]


def _join(stem: str, ending: str, pattern: str) -> str:
    """Stem + ending, respelling an ``-are`` stem before a front vowel."""
    if pattern != "are" or not ending or ending[0] not in _FRONT_VOWELS:
        return stem + ending
    for old, new in _ARE_RESPELL:
        if stem.endswith(old):
            return stem[: len(stem) - len(old)] + new + ending
    return stem + ending


def regular_forms(
    infinitive: str, pattern: str
) -> dict[tuple[str, str], tuple[str, ...]] | None:
    """Every cell a verb of this shape would have under ``pattern``.

    Each cell maps to *all* the forms the pattern accepts there, which is more
    than one where the pattern itself offers a choice — the ``-ere`` passato
    remoto takes both ``credetti`` and ``credei``.

    ``None`` if the infinitive is outside the three conjugations, or the
    pattern does not apply to it.
    """
    if pattern not in patterns_for(infinitive):
        return None
    index = PATTERNS.index(pattern)
    stem = infinitive[:-3]
    return {
        key: tuple(_join(stem, ending, pattern) for ending in endings[index])
        for key, endings in ENDINGS.items()
    }


# Cells to quote a spelling change from, most recognisable first.
_EXAMPLE_CELLS = (
    ("presente", "tu"),
    ("congiuntivo_presente", "io"),
    ("futuro_semplice", "io"),
)


@dataclass(frozen=True)
class Spelling:
    """A stem respelling that runs through a whole paradigm predictably."""

    old: str
    new: str
    before: str  # the vowels that trigger it, e.g. "e/i"
    examples: tuple[str, ...]

    def describe(self) -> str:
        return f"{self.old} → {self.new} before {self.before} ({', '.join(self.examples)})"


def spelling_change(infinitive: str) -> Spelling | None:
    """The one respelling this verb's stem needs, if any."""
    if "are" not in patterns_for(infinitive):
        return None
    index = PATTERNS.index("are")
    stem = infinitive[:-3]

    change = next(((o, n) for o, n in _ARE_RESPELL if stem.endswith(o)), None)
    if change is None:
        return None

    vowels = sorted(
        {
            ending[0]
            for e in ENDINGS.values()
            for ending in e[index]
            if ending and ending[0] in _FRONT_VOWELS
        }
    )
    # Deduplicated: several cells share an ending, so quoting them all would
    # print "cerchi, cerchi" instead of "cerchi, cercherò".
    examples: list[str] = []
    for key in _EXAMPLE_CELLS:
        if key not in ENDINGS:
            continue
        ending = ENDINGS[key][index][0]
        form = _join(stem, ending, "are")
        if form != stem + ending and form not in examples:
            examples.append(form)
    return Spelling(*change, before="/".join(vowels), examples=tuple(examples[:2]))


@dataclass(frozen=True)
class Classification:
    kind: str
    pattern: str | None = None
    spelling: Spelling | None = None

    @property
    def is_regular(self) -> bool:
        return self.kind != IRREGULAR

    def describe(self) -> str:
        """The verdict as a clause to follow the infinitive."""
        if self.kind == IRREGULAR:
            return "is an irregular verb."
        named = PATTERN_NAMES.get(self.pattern, self.pattern)
        if self.kind == REGULAR:
            return f"is a regular {named} verb."
        return (
            f"is a regular {named} verb, apart from a spelling change: "
            f"{self.spelling.describe()}."
        )


def classify(paradigm: Paradigm) -> Classification:
    """Predictable, predictable-but-respelt, or worth drilling.

    Deliberately strict: the cells must match one pattern exactly, so a verb
    carrying an extra accepted form anywhere is irregular. That form is the
    whole reason to drill it.
    """
    for pattern in patterns_for(paradigm.infinitive):
        expected = regular_forms(paradigm.infinitive, pattern)
        if expected is None or set(paradigm.cells) != set(expected):
            continue
        # Compared as sets: which of several equally regular forms the source
        # happens to list first is not a signal about the verb.
        if not all(
            set(cell.forms) == set(expected[key]) for key, cell in paradigm.cells.items()
        ):
            continue
        change = spelling_change(paradigm.infinitive)
        return (
            Classification(REGULAR_WITH_SPELLING, pattern, change)
            if change
            else Classification(REGULAR, pattern)
        )
    return Classification(IRREGULAR)


def is_regular(paradigm: Paradigm) -> bool:
    """True when the paradigm holds nothing the ending table doesn't predict."""
    return classify(paradigm).is_regular
